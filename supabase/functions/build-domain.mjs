#!/usr/bin/env node
/**
 * Prepares supabase/functions for the Deno runtime:
 *
 * 1. Bundles @st/domain → _shared/domain.mjs and @st/payments → _shared/payments.mjs
 *    (plain ESM; payments keeps `@st/domain` external so both share one copy).
 * 2. Collects packages/i18n/locales/<locale>/notifications.json → _shared/notifications.json
 *    (push-dispatch renders push copy in the recipient's locale) and the invite preview copy
 *    (common:sports, games:invite, invite:preview) → _shared/invite-copy.json (invite-preview).
 * 3. Writes import_map.json mapping every bare specifier the sources use
 *    (`@st/domain`, `@st/payments`, `#shared/*`, `#fn/*`) to files, so Deno
 *    resolves exactly what Node/tsc resolve through package.json "imports".
 *
 * Usage: node supabase/functions/build-domain.mjs [--check]
 *   --check  fail if import_map.json is out of date (CI), without writing bundles.
 */
import { build } from 'esbuild';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const shared = join(here, '_shared');
const check = process.argv.includes('--check');

function sourceFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === '_test' || name.startsWith('.')) continue;
    if (statSync(p).isDirectory()) out.push(...sourceFiles(p));
    else if (name.endsWith('.ts') && !name.endsWith('.test.ts')) out.push(p);
  }
  return out;
}

/** Bare specifiers used by function sources → file path relative to the import map. */
function importMap() {
  const imports = {
    '@st/domain': './_shared/domain.mjs',
    '@st/payments': './_shared/payments.mjs',
  };
  const re = /from\s+['"](#(?:shared|fn)\/[^'"]+)['"]/g;
  for (const file of sourceFiles(here)) {
    for (const m of readFileSync(file, 'utf8').matchAll(re)) {
      const spec = m[1];
      const target = spec.startsWith('#shared/') ? `./_shared/${spec.slice(8)}.ts` : `./${spec.slice(4)}.ts`;
      if (!existsSync(join(here, target))) throw new Error(`${relative(here, file)}: ${spec} → ${target} does not exist`);
      imports[spec] = target;
    }
  }
  return { imports: Object.fromEntries(Object.entries(imports).sort(([a], [b]) => a.localeCompare(b))) };
}

const mapPath = join(here, 'import_map.json');
const mapText = `${JSON.stringify(importMap(), null, 2)}\n`;
if (check) {
  const current = existsSync(mapPath) ? readFileSync(mapPath, 'utf8') : '';
  if (current !== mapText) {
    console.error('import_map.json is out of date: run node supabase/functions/build-domain.mjs');
    process.exit(1);
  }
  console.log('import_map.json is up to date');
  process.exit(0);
}

const common = {
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by supabase/functions/build-domain.mjs. Do not edit.' },
};
await build({ ...common, entryPoints: [join(root, 'packages/domain/src/index.ts')], outfile: join(shared, 'domain.mjs') });
await build({
  ...common,
  entryPoints: [join(root, 'packages/payments/src/index.ts')],
  outfile: join(shared, 'payments.mjs'),
  // `stripe` is type-only in @st/payments; the SDK is imported by index.ts as npm:stripe.
  external: ['@st/domain', 'stripe'],
});

const localesDir = join(root, 'packages/i18n/locales');
const catalogs = {};
if (existsSync(localesDir)) {
  for (const locale of readdirSync(localesDir).sort()) {
    const file = join(localesDir, locale, 'notifications.json');
    if (existsSync(file)) catalogs[locale] = JSON.parse(readFileSync(file, 'utf8'));
  }
}
if (!catalogs.en) console.warn('warning: no en notifications catalog found; push copy will use generic text');
writeFileSync(join(shared, 'notifications.json'), `${JSON.stringify(catalogs)}\n`);

// Invite rich-preview copy (invite-preview): common:sports, games:invite and the optional invite:preview.
const readJson = (file) => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null);
const inviteCopy = {};
if (existsSync(localesDir)) {
  for (const locale of readdirSync(localesDir).sort()) {
    const dir = join(localesDir, locale);
    if (!statSync(dir).isDirectory()) continue;
    const entry = {
      sports: readJson(join(dir, 'common.json'))?.sports,
      invite: readJson(join(dir, 'games.json'))?.invite,
      preview: readJson(join(dir, 'invite.json'))?.preview,
    };
    const kept = Object.fromEntries(Object.entries(entry).filter(([, v]) => v && typeof v === 'object'));
    if (Object.keys(kept).length > 0) inviteCopy[locale] = kept;
  }
}
writeFileSync(join(shared, 'invite-copy.json'), `${JSON.stringify(inviteCopy)}\n`);
writeFileSync(mapPath, mapText);
console.log(
  `built domain.mjs, payments.mjs, notifications.json (${Object.keys(catalogs).length} locales), invite-copy.json (${Object.keys(inviteCopy).length} locales), import_map.json`,
);
